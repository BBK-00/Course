// Regenerate the compact theory pages from python-theory-data.mjs.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { esc } from '../src/studio-render.js';
import { parseIndex } from '../src/studio-pages.js';
import { theory } from './python-theory-data.mjs';
import { visuals } from './python-theory-visuals.mjs';
import { ideSetup } from './python-ide-setup.mjs';

const catalogPath = new URL('../python/index.html', import.meta.url);
const original = readFileSync(catalogPath, 'utf8');
const filename = lesson => String(lesson.n).padStart(2, '0') + '-' + lesson.slug + '.html';
const byNumber = new Map(theory.map(lesson => [lesson.n, lesson]));
const version = '20261111-visual';
const catalog = original.replace(/<li>(?:<div class="topic soon"[^>]*>|<a class="topic"[^>]*data-theory-fallback[^>]*>)[\s\S]*?<\/li>/g, item => {
  const lesson = byNumber.get(Number(item.match(/<span class="num">(\d+)<\/span>/)?.[1]));
  if (!lesson) return item;
  const title = item.match(/<span class="t">([\s\S]*?)<\/span>/)[1];
  return '<li><a class="topic" href="' + filename(lesson) + '" data-theory-fallback>\n'
    + '      <div class="topic-top"><span class="num">' + lesson.n + '</span><span class="badge open">Ашық</span></div>\n'
    + '      <span class="t">' + title + '</span><span class="s">' + esc(lesson.lead) + '</span>\n'
    + '      <div class="tags"><span class="tag">Теория</span><span class="tag">Өзіндік жаттығу</span></div>\n'
    + '      <span class="go">Сабақты ашу →</span>\n    </a></li>';
}).replace(/<div class="stat"><b>\d+<\/b><span>ашық<\/span><\/div>/, '<div class="stat"><b>24</b><span>ашық</span></div>')
  .replace(/\s*<div class="stat"><b>\d+<\/b><span>әзірленуде<\/span><\/div>/, '')
  .replace(/studio-topics\.js\?v=[^"]+/, 'studio-topics.js?v=' + version);

const links = parseIndex(catalog, 'python');
if (links.length !== 24 || links.some(t => !t.open) || theory.some(lesson => links.find(t => t.num === lesson.n)?.path !== '/python/' + filename(lesson).replace(/\.html$/, ''))) {
  throw new Error('Python catalog must link all 24 lessons, including every generated theory page.');
}

function render(lesson) {
  const { n, title, lead, ideas, code, input, steps, tip, quiz } = lesson;
  const visual = visuals.get(n);
  const [, expression, explanation, tiles] = visual.cases[0];
  const [question, options, correct, reason] = quiz;
  const data = JSON.stringify({ steps, correct, reason, cases: visual.cases }).replace(/</g, '\\u003c');
  const tile = ([label, value, state = '']) => `<div class="pt-tile" data-state="${state}"><span>${esc(label)}</span><strong>${esc(value)}</strong></div>`;
  const highlighted = line => line.split(/("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|#.*$|\b(?:for|while|if|elif|else|in|and|or|not|break|continue|True|False|None)\b|\b(?:print|input|int|float|str|len|range|sum|type|sorted)\b|\b\d+(?:\.\d+)?\b)/g)
    .map((word, index) => index % 2 ? '<span class="pt-token ' + (/^["']/.test(word) ? 'string' : word.startsWith('#') ? 'comment' : /^\d/.test(word) ? 'number' : 'keyword') + '">' + esc(word) + '</span>' : esc(word)).join('');
  const neighbor = (number, label, className) => {
    const target = links.find(link => link.num === number);
    return target ? '<a class="btn ' + className + '" href="' + target.path + '">' + label + '</a>' : '';
  };
  return `<!doctype html>
<!-- Generated by scripts/build-python-theory.mjs from scripts/python-theory-data.mjs -->
<html lang="kk">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${n}-сабақ. ${esc(title)} — Python</title>
<meta name="description" content="${esc(lead)}">
<link rel="stylesheet" href="../assets/lesson.css">
<link rel="stylesheet" href="../assets/student.css?v=20261111">
<link rel="stylesheet" href="../assets/python-theory.css?v=${version}">
<link rel="stylesheet" href="../assets/python-practice.css?v=1">
<link rel="stylesheet" href="../assets/python-lesson-tabs.css?v=1">
</head>
<body class="student-lesson python-theory" data-tone="${visual.tone}">
<a class="skip-link" href="#main">Мазмұнға өту</a>
<header class="topbar"><div class="topbar-in">
  <a class="pt-brand" href="./"><span aria-hidden="true">←</span> Python</a>
  <span class="pt-course">${n} / 24 сабақ</span>
  <nav class="pt-lesson-tabs" role="tablist" aria-label="Сабақ бөлімдері">
    <a href="#theory" id="pt-tab-theory" role="tab" aria-controls="theory" aria-selected="true">Түсіндіру</a>
    <a href="#task" id="pt-tab-task" role="tab" aria-controls="task" aria-selected="false">Тапсырмалар</a>
  </nav>
</div></header>
<main class="wrap" id="main">
  <div id="theory" role="tabpanel" aria-labelledby="pt-tab-theory">
  <section class="pt-hero" aria-labelledby="title">
    <div>
      <span class="pt-kicker">PYTHON · ${String(n).padStart(2, '0')}-САБАҚ</span>
      <h1 id="title">${esc(title)}</h1>
      <p class="pl-lead">${esc(lead)}</p>
      <div class="pt-hero-actions">
        ${n === 1 ? '<a class="btn" href="#setup">Орнату нұсқаулығы ↓</a>' : ''}
        <a class="btn" href="#visual">Көрнекі мысалды ашу <span aria-hidden="true">↘</span></a>
      </div>
    </div>
    <div class="pt-hero-aside">
      <span>САБАҚТАҒЫ МЫСАЛ</span>
      <code>${esc(expression)}</code>
      <div class="pt-hero-values">${tiles.slice(0, 6).map(([, value, state = '']) => '<span data-state="' + state + '">' + esc(value) + '</span>').join('')}</div>
    </div>
  </section>
  <div class="pt-layout">
  <nav class="pt-outline" aria-label="Сабақ мазмұны">
    <b>Сабақ мазмұны</b>
    ${n === 1 ? '<a href="#setup">Орнату</a>' : ''}
    <a href="#visual">Көрнекі мысал</a>
    <a href="#ideas">Теория</a>
    <a href="#example">Кодтың орындалуы</a>
    <a href="#check">Бекіту</a>
    <a href="#task">Тапсырмалар</a>
  </nav>
  <div class="pt-content">
${n === 1 ? ideSetup : ''}
  <section class="pt-section pt-visual" id="visual" aria-labelledby="visual-title">
    <span class="pt-overline">ТАҢДАП КӨР</span>
    <h2 id="visual-title">${esc(visual.title)}</h2>
    <p>${esc(visual.intro)}</p>
    <div class="pt-choices" role="group" aria-label="Көрнекі мысал нұсқалары" hidden>${visual.cases.map(([name], i) => '<button type="button" class="btn" aria-pressed="' + String(i === 0) + '">' + esc(name) + '</button>').join('')}</div>
    <div class="pt-visual-demo" data-kind="${visual.kind}">
      <div class="pt-board" data-kind="${visual.kind}" id="visualBoard">${tiles.map(tile).join('')}</div>
      <div class="pt-visual-result"><code id="visualCode">${esc(expression)}</code><p id="visualCaption" role="status">${esc(explanation)}</p></div>
    </div>
  </section>
  <section class="pt-section" id="ideas" aria-labelledby="ideas-title">
    <span class="pt-overline">ҚЫСҚА ТЕОРИЯ</span>
    <h2 id="ideas-title">Негізгі ұғымдар</h2>
    <div class="pt-ideas">
${ideas.map(([heading, description, snippet], i) => `      <article><span class="pt-index">${String(i + 1).padStart(2, '0')}</span><div><h3>${esc(heading)}</h3><p>${esc(description)}</p></div><code>${esc(snippet)}</code></article>`).join('\n')}
    </div>
  </section>
  <section class="pt-section pt-example" id="example" aria-labelledby="example-title">
    <span class="pt-overline">КОДТЫ БАҚЫЛА</span>
    <h2 id="example-title">Қадамдық мысал</h2>
    <p>Кодтың негізгі қадамдарын қарап, мәндер мен экрандағы нәтиженің өзгерісін бақыла.</p>
${input.length ? '    <p class="pt-input"><b>Мысалдағы енгізу</b> ' + input.map(value => '<code>' + esc(value) + '</code>').join(' ') + '</p>\n' : ''}    <div class="pt-lab">
      <div class="pt-code"><span class="pt-window-label">Python коды</span>
        <pre><code>${code.map((line, i) => '<span class="pt-line"><span class="pt-line-no" aria-hidden="true">' + (i + 1) + '</span><span>' + highlighted(line) + '</span></span>').join('')}</code></pre>
      </div>
      <div class="pt-stage">
        <span class="pt-window-label">Орындалу көрінісі</span>
        <div class="pt-values" id="traceValues"></div>
        <p id="traceCaption" role="status">Бірінші қадамды бастауға дайын.</p>
        <div class="pt-output"><span class="pt-window-label">Экран</span><pre id="traceOutput">Әзірге бос</pre></div>
      </div>
    </div>
    <div class="pt-controls" hidden>
      <button type="button" class="btn" id="traceBack">← Артқа</button>
      <button type="button" class="btn primary" id="traceNext">Келесі қадам →</button>
      <button type="button" class="btn" id="tracePlay">▶ Ойнату</button>
      <span id="traceCount"></span>
    </div>
    <noscript><p>Кодтың нәтижесі</p><pre>${esc(steps.at(-1)[3])}</pre></noscript>
  </section>
  <aside class="pt-tip"><b>Есте сақта</b><p>${esc(tip)}</p></aside>
  <section class="pt-section pt-check" id="check" aria-labelledby="check-title">
    <h2 id="check-title">Өзіңді тексер</h2>
    <p>${esc(question)}</p>
    <div class="pt-options" role="group" aria-label="Жауап нұсқалары" hidden>${options.map(option => '<button type="button" class="btn">' + esc(option) + '</button>').join('')}</div>
    <p id="checkFeedback" role="status"></p>
    <noscript><p>${esc(reason)}</p></noscript>
  </section>
  </div>
  </div>
  </div>
  <section id="task" class="pp-practice" role="tabpanel" aria-labelledby="pt-tab-task" data-python-practice="${n}" data-practice-rotation></section>
  <nav class="pt-neighbors" aria-label="Басқа сабақтар">
    ${neighbor(n - 1, '← Алдыңғы сабақ', '')}
    <a class="btn" href="./">Барлық тақырып</a>
    ${neighbor(n + 1, 'Келесі сабақ →', 'primary')}
  </nav>
</main>
<footer class="pt-footer">Python · Бақытжанов Бекет Қайратұлы</footer>
<script type="application/json" id="theoryData">${data}</script>
<script src="../assets/python-theory.js?v=${version}"></script>
<script src="../assets/python-lesson-tabs.js?v=1"></script>
<script src="../assets/python-practice.js?v=2"></script>
</body>
</html>
`;
}

for (const lesson of theory) {
  const path = new URL('../python/' + filename(lesson), import.meta.url);
  const html = render(lesson);
  if (!existsSync(path) || readFileSync(path, 'utf8') !== html) writeFileSync(path, html);
}
if (catalog !== original) writeFileSync(catalogPath, catalog);
console.log('Python: ' + theory.length + ' theory pages generated, 24 lessons linked.');
