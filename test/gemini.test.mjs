import assert from 'node:assert/strict';
import { geminiJson, geminiKeys, GeminiError } from '../src/gemini.js';
import { gradeHomeworkPhoto } from '../src/pyapi.js';
const original = globalThis.fetch, calls = [];
const keys = ['test-key-one','test-key-two','test-key-three'];
let next = 0;
const DB = { prepare: () => ({ bind: (_initial,count) => ({ first: async () => { const old = next % count; next = (old+1)%count; return {next_key:next}; } }) }) };
const env = { GEMINI_API_KEY: keys.join(','), DB };
const response = (status, body) => new Response(JSON.stringify(body), {status});
const good = data => response(200,{candidates:[{content:{parts:[{thought:true,text:'private reasoning'},{text:JSON.stringify(data)}]}}]});
const schema = {type:'OBJECT',properties:{ok:{type:'BOOLEAN'}}};
const run = () => geminiJson(env,[{text:'test'}],schema);
try {
  assert.deepEqual(geminiKeys({GEMINI_API_KEY:'"one",two;one',GEMINI_API_KEY_2:'three',GEMINI_API_KEYS:'["two","four"]'}),['one','two','four','three']);
  globalThis.fetch = async (_url,options) => {calls.push(options.headers['x-goog-api-key']);assert(options.signal);return good({ok:true});};
  await Promise.all([run(),run(),run(),run(),run(),run()]);
  assert.deepEqual(calls,[...keys,...keys],'Successful requests rotate through all three keys');
  next=0;calls.length=0;
  globalThis.fetch = async (_url,o) => {const key=o.headers['x-goog-api-key'];calls.push(key);return key===keys[0]?response(429,{error:{status:'RESOURCE_EXHAUSTED'}}):good({ok:true});};
  assert.deepEqual(await run(),{ok:true});assert.deepEqual(calls,keys.slice(0,2));
  next=0;calls.length=0;
  globalThis.fetch = async (url,o) => {calls.push({url,key:o.headers['x-goog-api-key']});return url.includes('gemini-2.5-flash:')?response(503,{error:{status:'UNAVAILABLE'}}):good({ok:true});};
  await run();assert.equal(calls.length,2,'Model overload goes directly to another model');
  assert(calls[1].url.includes('gemini-flash-lite-latest'));
  next=0;calls.length=0;
  globalThis.fetch = async (_url,o) => {const k=o.headers['x-goog-api-key'];calls.push(k);return k===keys[0]?response(403,{error:{status:'PERMISSION_DENIED'}}):good({ok:true});};
  await run();assert.deepEqual(calls,keys.slice(0,2));
  next=0;calls.length=0;
  globalThis.fetch = async (_url,o) => {calls.push(o.headers['x-goog-api-key']);return calls.length===1?good({score:'25',comment:'bad type'}):good({score:24,comment:'Жақсы жұмыс'});};
  assert.equal((await gradeHomeworkPhoto(env,'A'.repeat(3000),'image/jpeg')).score,24,'Malformed grade never becomes an automatic zero');
  next=0;
  globalThis.fetch = async () => {throw new DOMException('timed out','TimeoutError');};
  await assert.rejects(run(),e=>e instanceof GeminiError&&e.kind==='timeout');
  globalThis.fetch = async () => response(429,{error:{message:'hidden key detail'}});
  await assert.rejects(run(),e=>e.kind==='quota'&&!JSON.stringify(e).includes('hidden key'));
  await assert.rejects(geminiJson({},[],schema),e=>e.kind==='config');
  globalThis.fetch=async()=>{throw new Error('Stub must not use the network');};
  assert.equal((await gradeHomeworkPhoto({GEMINI_STUB:'1'},'photo','image/png')).score,20);
  console.log('Gemini: key formats, atomic rotation, quota/auth fallback, model overload fallback, timeouts, grade validation and secret-free errors passed.');
} finally { globalThis.fetch=original; }
