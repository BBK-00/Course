import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {memoryD1} from './d1-memory.mjs';
import worker from '../src/index.js';
const DB=memoryD1(),env={DB,TEACHER_PASSWORD:'test123'};
const call=async(p,b,t)=>{const r=await worker.fetch(new Request('https://qa.invalid/api/'+p,{method:b?'POST':'GET',headers:{'Content-Type':'application/json',...(t?{Authorization:'Bearer '+t}:{})},...(b?{body:JSON.stringify(b)}:{})}),env,{});return {http:r.status,...await r.json()};};
const token=(await call('teacher/login',{password:'test123'})).token,T=(p,b)=>call('teacher/'+p,b,token);
const group=(await T('groups',{name:'Analytics QA'})).groups[0];
const students=(await T('students',{group_id:group.id,names:Array.from({length:8},(_,i)=>'Student '+i).join('\n')})).groups[0].students;
await T('session/start',{topic:'P4',group_id:group.id});const session=(await T('live')).session.id;
for(const s of students)await T('attendance',{session_id:session,student_id:s.id,present:true});
const put=(s,item,n,frac,diag=[])=>DB.sqlite.prepare('INSERT INTO py_attempts(session_id,student_id,item,n,at,frac,detail,signals) VALUES(?,?,?,?,?,?,?,?)').run(session,s.id,item,n,123456,frac,JSON.stringify({diag}),'{}');
students.forEach((s,i)=>{
  put(s,31,1,i===1?.5:i<6?0:1,[{skill:'input'},{skill:'input'}]);
  if(i===0)put(s,31,2,1);
  put(s,11,1,i<2?0:1,[{skill:'add'}]);
});
put(students[0],32,1,0,[{skill:'syntax'}]);
const before=DB.sqlite.prepare('SELECT COUNT(*) n,SUM(frac) score FROM py_attempts').get();
assert.equal((await call('teacher/py_stats?session='+session)).http,401);
const data=await T('py_stats?session='+session),item=data.allItems.find(i=>i.id===31);
assert.equal(item.label,'2.1');assert.equal(item.sent,8);assert.equal(item.firstCorrect,2);assert.equal(item.corrected,1);assert.equal(item.unresolved,5);
assert.equal(item.struggling.length,5);assert(!item.struggling.some(s=>s.id===students[0].id));
assert(item.struggling.some(s=>s.id===students[1].id),'Partially solved answers still need help');
assert.equal(item.skills.find(s=>s.skill==='input').n,5,'Duplicate diagnostics count a student once');
assert(item.skills[0].tip);assert(data.allItems.some(i=>i.id===11),'Quick answers are included');
assert(data.allItems.some(i=>i.task===4),'Final test questions are included');
assert.deepEqual(DB.sqlite.prepare('SELECT COUNT(*) n,SUM(frac) score FROM py_attempts').get(),before,'Analytics is read-only');
const context={window:{}};vm.runInNewContext(fs.readFileSync('teacher/analysis.js','utf8'),context);
const report=context.window.TeacherAnalysis.insights(data);
assert.equal(report.alerts[0].id,31);assert.equal(report.hard[0].id,31);
assert.equal(report.answers,17);assert.equal(report.first+report.fixed+report.wrong,report.answers);
assert(!report.alerts.some(i=>i.id===32),'One response cannot justify a class-wide warning');
assert.equal(context.window.TeacherAnalysis.insights({present:20,allItems:[{id:1,sent:3,unresolved:3}]}).alerts.length,0,'Sparse participation needs more evidence');
assert.equal(context.window.TeacherAnalysis.insights({allItems:[]}).answers,0);
console.log('Analytics: exact unique student counts, first/corrected/unresolved partitions, all tasks, no sparse-data alarms, teaching tips, authentication and read-only preservation passed.');
