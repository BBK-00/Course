import assert from 'node:assert/strict';
import worker from '../src/index.js';
import {memoryD1} from './d1-memory.mjs';
import {lessonOf} from '../src/py.js';
const DB=memoryD1(),env={DB,TEACHER_PASSWORD:'test123',GEMINI_STUB:'1'};
const call=async(p,b,t)=>{const r=await worker.fetch(new Request('https://qa.invalid/api/'+p,{method:b?'POST':'GET',headers:{'Content-Type':'application/json',...(t?{Authorization:'Bearer '+t}:{})},...(b?{body:JSON.stringify(b)}:{})}),env,{});return {status:r.status,...await r.json()};};
const login=await call('teacher/login',{password:'test123'}),T=(p,b)=>call('teacher/'+p,b,login.token);
const g=(await T('groups',{name:'Revision QA'})).groups[0];
const student=(await T('students',{group_id:g.id,names:'Student'})).groups[0].students[0];
await T('session/start',{topic:'P4',group_id:g.id});const live=await T('live'),sid=live.session.id;
const token=(await call('join',{student_id:student.id,code:live.session.code,device:'revision-test'})).token;
await T('pywin',{task:1,action:'start',minutes:7});
const lesson=lessonOf('P4',1),[wrong,correct,unsent]=lesson[0].items;
const secondWrong=lesson[0].items[3];
assert((await call('py/submit',{quiz:{[wrong.id]:'99999',[correct.id]:correct.ans,[secondWrong.id]:'99999'}},token)).ok);
assert.equal((await call('py/data',null,token)).state[wrong.id].canRevise,false);
assert.equal((await call('py/submit',{item:wrong.id,choice:wrong.ans},token)).error,'no_tries');
await T('pywin',{task:0,action:'start',minutes:10});
const data=await call('py/data',null,token);assert(data.state[wrong.id].canRevise);assert(!data.state[correct.id].canRevise);
assert.equal((await call('py/submit',{item:unsent.id,choice:unsent.ans},token)).error,'time_over');
DB.sqlite.prepare('UPDATE py_attempts SET at=at-9').run();
const fix=await call('py/submit',{item:wrong.id,choice:wrong.ans},token);assert(fix.ok);assert.equal(fix.results[0].pts,0.5);assert.equal(fix.scores[1].pts,1.5);
assert.equal((await call('py/submit',{item:correct.id,choice:'0'},token)).error,'full');
const reloaded=await call('py/data',null,token);assert.equal(reloaded.state[wrong.id].best,1);assert.equal(reloaded.state[wrong.id].tries,2);
assert.equal(DB.sqlite.prepare('SELECT COUNT(*) n FROM submissions WHERE task=6').get().n,0,'Revision preserves the original 100-point tasks');
DB.sqlite.prepare('UPDATE py_wins SET until_at=unixepoch()-90 WHERE task=0').run();
assert.equal((await call('py/submit',{item:wrong.id,choice:wrong.ans},token)).error,'full');
assert(['time_over','no_tries'].includes((await call('py/submit',{item:secondWrong.id,choice:secondWrong.ans},token)).error),'Expired revision must reject further corrections');
console.log('Revision: locked before stage, wrong answers only, typed retry, original-task points, correct/unsent protection and persisted history passed.');
